using UnityEngine;

public class NetworkPersistence : MonoBehaviour
{
    public static NetworkPersistence Instance { get; private set; }

    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }

        Instance = this;

        DontDestroyOnLoad(gameObject);
    }
}
